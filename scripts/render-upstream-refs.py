#!/usr/bin/env python3
"""Synchronize the upstream_ref choices of the firmware build Issue Form.

Reads the tag and branch names of fanchmwrt/fanchmwrt, keeps released version
tags (``v<major>.<minor>[.<patch>...]``; ``-rc`` prereleases and unrelated tags
are dropped) and sorts them newest first. A branch named ``fanchmwrt-<version>``
is listed directly before the tag of the same version, so a version that also
has a maintenance branch reads::

    fanchmwrt-25.12.6
    v25.12.6
    fanchmwrt-25.12.4
    v25.12.4

The generated blocks of the Issue Form and of the ``workflow_dispatch`` inputs
in build.yml are then rewritten from that list, so a manual run offers exactly
the same choices as an Issue request. The default follows the newest version and
prefers its maintenance branch, because that is what a stock configuration
needs: the plain tag carries no private fanchmwrt layer, so any config asking
for fwxd or luci-app-fwx-app-center fails in verify-build.sh. When a version has
no branch the tag is used, and the device backport repository accepts either one
because it verifies that the selected commit descends from the pinned tag.

The generated blocks are delimited by marker comments; everything outside them
is preserved byte for byte.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

SYNC_SOURCE = "auto-generated by .github/workflows/sync-upstream-refs.yml"
OPTIONS_BEGIN = f"# BEGIN upstream_ref options ({SYNC_SOURCE})"
OPTIONS_END = f"# END upstream_ref options ({SYNC_SOURCE})"
DEFAULT_BEGIN = f"# BEGIN upstream_ref default ({SYNC_SOURCE})"
DEFAULT_END = f"# END upstream_ref default ({SYNC_SOURCE})"

VERSION_TAG_RE = re.compile(r"^v(\d+(?:\.\d+)*)$")
VERSION_BRANCH_RE = re.compile(r"^fanchmwrt-(\d+(?:\.\d+)*)$")
MAX_CHOICES = 100


def fail(message: str) -> None:
    print(f"Cannot synchronize upstream_ref choices: {message}", file=sys.stderr)
    raise SystemExit(2)


def load_names(path: str) -> list[str]:
    try:
        if path == "-":
            payload = json.load(sys.stdin)
        else:
            with open(path, encoding="utf-8") as handle:
                payload = json.load(handle)
    except (OSError, ValueError) as error:
        fail(f"cannot read {path}: {error}")

    if not isinstance(payload, list):
        fail(f"{path} must contain a JSON list")

    names: list[str] = []
    for entry in payload:
        if isinstance(entry, str):
            names.append(entry)
        elif isinstance(entry, dict) and isinstance(entry.get("name"), str):
            names.append(entry["name"])
        else:
            fail(f"{path} contains an unsupported entry: {entry!r}")
    return names


def released_versions(names: list[str], limit: int) -> list[str]:
    versions = {match.group(1): name for name in names if (match := VERSION_TAG_RE.fullmatch(name))}
    ordered = sorted(versions, key=lambda value: tuple(int(part) for part in value.split(".")), reverse=True)
    return [versions[value] for value in ordered[:limit]]


def version_branches(names: list[str]) -> dict[str, str]:
    branches: dict[str, str] = {}
    for name in names:
        match = VERSION_BRANCH_RE.fullmatch(name)
        if match:
            branches[match.group(1)] = name
    return branches


def interleaved_choices(versions: list[str], branches: dict[str, str]) -> list[str]:
    """Pair every release tag with its maintenance branch, branch first."""
    choices: list[str] = []
    for name in versions:
        branch = branches.get(name[1:])
        if branch:
            choices.append(branch)
        choices.append(name)
    return choices


def parse_downgrades(path: str | None, versions: list[str]) -> dict[str, str]:
    """Fold upstream's ``manifest.json`` maintenance table into a per-version map.

    Upstream is authoritative: when it publishes a release that repairs the
    private ``fanchmwrt-`` maintenance layer, the builder must stop offering that
    branch until the repair. The mirror holds ``{"maintenance": {version:
    behaviour}}`` where ``maintenance`` means "this release repaired the layer,
    every older branch predates the repair" and ``silent`` means "this release has
    no usable branch". A missing or unreadable mirror leaves every version
    ``normal``.
    """
    claims: dict[str, str] = {}
    if path:
        try:
            with open(path, encoding="utf-8") as handle:
                payload = json.load(handle)
        except FileNotFoundError:
            payload = {}
        except (OSError, ValueError) as error:
            fail(f"cannot read {path}: {error}")
        table = payload.get("maintenance") if isinstance(payload, dict) else None
        known = set(versions)
        for version, entry in (table or {}).items() if isinstance(table, dict) else []:
            behaviour = entry.get("behaviour") if isinstance(entry, dict) else entry
            if behaviour == "normal":
                continue
            if behaviour not in {"maintenance", "silent"}:
                fail(f"unknown downgrade behaviour {behaviour!r} for {version!r}")
            if version not in known:
                continue
            claims[version] = behaviour
    return {version: claims.get(version, "normal") for version in versions}


def withheld(choice: str, versions: list[str], behaviours: dict[str, str]) -> bool:
    """True when a maintenance branch must not be offered.

    Two upstream claims withdraw a branch: ``silent`` on its own version (the
    layer has no usable branch yet) and ``maintenance`` on a newer version (the
    older branch predates the repair). The newest version is therefore only
    withdrawn by its own ``silent`` claim.
    """
    if not choice.startswith("fanchmwrt-"):
        return False
    version = "v" + choice[len("fanchmwrt-"):]
    if version not in versions:
        return True
    if behaviours.get(version) == "silent":
        return True
    return any(behaviours.get(later) == "maintenance" for later in versions[: versions.index(version)])


def read_text(path: str) -> tuple[str, list[str]]:
    try:
        with open(path, encoding="utf-8", newline="") as handle:
            text = handle.read()
    except OSError as error:
        fail(f"cannot read {path}: {error}")
    return text, text.splitlines()


def block_bounds(path: str, lines: list[str], begin: str, end: str) -> tuple[int, int, str]:
    begin_index = next((index for index, line in enumerate(lines) if line.strip() == begin), None)
    end_index = next((index for index, line in enumerate(lines) if line.strip() == end), None)
    if begin_index is None or end_index is None:
        fail(f"{path} is missing the {begin!r} or {end!r} marker")
    if end_index <= begin_index:
        fail(f"{path} has its markers in the wrong order")
    line = lines[begin_index]
    return begin_index, end_index, line[: len(line) - len(line.lstrip())]


def current_rows(path: str, begin: str, end: str) -> list[str]:
    _, lines = read_text(path)
    begin_index, end_index, _ = block_bounds(path, lines, begin, end)
    return [line.strip() for line in lines[begin_index + 1 : end_index]]


def replace_block(path: str, begin: str, end: str, rows: list[str]) -> bool:
    text, lines = read_text(path)
    begin_index, end_index, indent = block_bounds(path, lines, begin, end)
    replacement = [f"{indent}{begin}"] + [f"{indent}{row}" for row in rows] + [f"{indent}{end}"]
    updated = "\n".join(lines[:begin_index] + replacement + lines[end_index + 1 :])
    if text.endswith("\n"):
        updated += "\n"
    if updated == text:
        return False
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(updated)
    return True


def write_output(values: dict[str, str]) -> None:
    output_path = os.environ.get("GITHUB_OUTPUT")
    if not output_path:
        return
    with open(output_path, "a", encoding="utf-8", newline="\n") as output:
        for key, value in values.items():
            output.write(f"{key}={value}\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tags", required=True, help="JSON tag list, or - for stdin")
    parser.add_argument("--branches", help="JSON branch list; fanchmwrt-<version> entries pair with their tag")
    parser.add_argument("--issue-form", required=True, help="Issue Form YAML carrying the choices")
    parser.add_argument("--workflow-file", help="Workflow whose dispatch choices and default are refreshed")
    parser.add_argument("--limit", type=int, default=20, help="Maximum number of releases (default: 20)")
    parser.add_argument(
        "--downgrade",
        metavar="PATH",
        help="Mirror of the upstream manifest whose maintenance table withholds branches",
    )
    parser.add_argument("--check", action="store_true", help="Report changes without writing any file")
    args = parser.parse_args()

    if not 1 <= args.limit <= MAX_CHOICES:
        fail(f"--limit must be between 1 and {MAX_CHOICES}")

    versions = released_versions(load_names(args.tags), args.limit)
    if not versions:
        fail("the upstream tag list contains no released version tag")
    branches = version_branches(load_names(args.branches)) if args.branches else {}
    behaviours = parse_downgrades(args.downgrade, versions)
    choices = [
        choice
        for choice in interleaved_choices(versions, branches)
        if not withheld(choice, versions, behaviours)
    ]
    if len(choices) > MAX_CHOICES:
        fail(f"{len(choices)} choices exceed the {MAX_CHOICES} the renderer allows")
    latest = versions[0]
    # Default to the maintenance branch, not the bare tag: the tag has no private
    # fanchmwrt layer, so a stock configuration (fwxd, luci-app-fwx-app-center)
    # would fail verification on the very first default run. Fall back to the tag
    # only when that version has no branch.
    withheld_branches = {choice for choice in branches.values() if withheld(choice, versions, behaviours)}
    if withheld_branches:
        print(f"withheld by upstream manifest: {', '.join(sorted(withheld_branches))}", file=sys.stderr)
    # Prefer the maintenance branch, fall back to the bare tag when upstream says
    # that branch carries no usable private layer yet.
    default_ref = branches.get(latest[1:], latest)
    if default_ref in withheld_branches:
        default_ref = latest
    # The Issue Form dropdown takes an index, the workflow_dispatch input takes a
    # name. The form's index 0 is the first choice, which is the maintenance
    # branch whenever the newest version has one -- the same rule as above, so
    # an Issue request and a manual run start from the same ref. Only when the
    # two disagree is there something to worry about, and that is what the
    # assertion below rejects.
    default_index = 0
    if choices[default_index] != default_ref:
        fail(
            f"the first choice {choices[default_index]!r} is not the dispatch default "
            f"{default_ref!r}; the Issue Form can only preselect index 0"
        )
    rows = [f"- {name}" for name in choices]
    targets = [
        (args.issue_form, OPTIONS_BEGIN, OPTIONS_END, rows),
    ]
    if args.workflow_file:
        targets.append((args.workflow_file, OPTIONS_BEGIN, OPTIONS_END, rows))
        targets.append((args.workflow_file, DEFAULT_BEGIN, DEFAULT_END, [f"default: {default_ref}"]))

    if args.check:
        changed = any(current_rows(path, begin, end) != rows for path, begin, end, rows in targets)
    else:
        changed = False
        for path, begin, end, rows in targets:
            changed = replace_block(path, begin, end, rows) or changed

    write_output({"changed": "1" if changed else "0", "latest": latest, "count": str(len(choices))})
    print(f"latest={latest} choices={len(choices)} changed={'1' if changed else '0'}")
    if not args.check:
        for name in choices:
            print(f"  {name}")


if __name__ == "__main__":
    main()
